#!/usr/bin/env python
"""Figure: ground truth | model | superposition, diagonal two-hole plate, FI.

Compares the model's two-hole rollout with a superposition of the two single-hole
solutions, selected by --baseline:

  sum_true   A + B of the single-hole FE solutions (default)
  sum_pred   A + B of the model's single-hole predictions
  fit_true   least-squares a*A + b*B + c of the FE solutions
  fit_pred   least-squares a*A + b*B + c of the model's predictions

All panels are rendered on the two-hole element footprints with the recipe of
tools/export_fields_for_tikz.py (_render_mesh_panel_png: viridis, 0 to 3, edge
alpha 0.15, lw 0.3), one flat colour per element. The single-hole solutions are
interpolated onto the two-hole element centroids per ply, which affects only the
superposition panel.

Usage:
  python tools/make_superposition_figure.py \
      --out <figure dir> --ply 1 --times 0.52,0.79
"""
import argparse
import os
import sys

import numpy as np
from scipy.interpolate import griddata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

from export_fields_for_tikz import (            # noqa: E402
    read_vtu_full, _hex_footprint_quads, _frame_files, _vtu_time,
    _render_mesh_panel_png,
)

RUN_AB = "results/extrap_twohole_diag_vtk"
RUN_A = "results/attn_onehole_diag_a_step22"
RUN_B = "results/attn_onehole_diag_b_step22"
RUN_0 = "results/extrap_nohole_vtk"      # unnotched plate, the reference state
THR = 1.0


def frame_times(run):
    files = _frame_files(os.path.join(ROOT, run), "sim_000")
    t = np.array([_vtu_time(f) or 0.0 for f in files], float)
    return files, (t / t.max() if t.max() > 0 else t)


def ply_interp(src_c, src_v, dst_c, ps, pd, plies):
    """Per-ply interpolation of an element field onto other element centroids."""
    out = np.full(len(dst_c), np.nan)
    for p in plies:
        s, d = ps == p, pd == p
        if s.sum() < 4 or d.sum() == 0:
            continue
        v = griddata(src_c[s, :2], src_v[s], dst_c[d, :2], method="linear")
        bad = ~np.isfinite(v)
        if bad.any():
            v[bad] = griddata(src_c[s, :2], src_v[s], dst_c[d][bad, :2],
                              method="nearest")
        out[d] = v
    return out


def dice(pred, true):
    den = float(pred.sum() + true.sum())
    return 2.0 * float(np.logical_and(pred, true).sum()) / den if den else np.nan


SUP_TITLE = {
    "sum_true": r"Superposition of the\\two single-hole solutions",
    "sum_pred": r"Superposition of the\\two single-hole predictions",
    "fit_true": r"Fitted superposition of the\\two single-hole solutions",
    "fit_pred": r"Fitted superposition of the\\two single-hole predictions",
    "pert_true": r"Superposition of the\\two single-hole solutions",
    "pert_pred": r"Superposition of the\\two single-hole predictions",
}

# The perturbation form. Adding two ABSOLUTE fields counts the far-field state
# twice, which raises the background of the whole panel and is not what
# superposition means: in a linear problem one superposes the PERTURBATIONS each
# feature introduces on a common reference state. With the unnotched plate as
# that reference,
#     FI_sup = FI_0 + (FI_A - FI_0) + (FI_B - FI_0) = FI_A + FI_B - FI_0 ,
# which removes the double-counted background. This is both the better-posed
# baseline and the one a careful practitioner would form, so it is the default.
PERTURBATION = {"pert_true", "pert_pred"}

HEAD = r"""% Auto-generated by tools/make_superposition_figure.py -- do not edit.
% Diagonal two-hole plate, failure index, ply {ply}. Baseline: {baseline}.
% Same element-footprint PolyCollection recipe, viridis colormap and 0..3
% failure-index scale as Figures 14 and 15, so the panels are comparable.
\begin{{tikzpicture}}
\begin{{groupplot}}[
  group style={{group size=3 by {nrow}, horizontal sep=4.0mm,
                vertical sep=3.0mm}},
  % width AND height are both set explicitly, and "axis equal image" is not
  % used: that key derives the height from the data aspect ratio and leaves the
  % height key unset, so the colorbar below cannot read
  % /pgfplots/parent axis height and comes out far shorter than the panels.
  % The domain is exactly square (-17..17 in both directions), so equal width
  % and height preserve the aspect anyway.
  width=0.26\linewidth, height=0.26\linewidth, scale only axis,
  enlargelimits=false, xtick=\empty, ytick=\empty,
  colormap/viridis, point meta min=0, point meta max=3,
  title style={{font=\scriptsize, align=center, text width=0.30\linewidth,
                yshift=0.4mm}},
  ylabel style={{font=\scriptsize}},
]
"""

CELL = r"""\nextgroupplot[{opts}]
\addplot graphics[xmin={x0:.4g}, xmax={x1:.4g}, ymin={y0:.4g}, ymax={y1:.4g}]
  {{{png}}};
"""

TAIL = r"""\end{groupplot}
\end{tikzpicture}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--ply", type=int, default=1)
    ap.add_argument("--times", default="0.79",
                    help="comma-separated pseudo-times, one row each")
    ap.add_argument("--baseline", default="sum_true",
                    choices=sorted(SUP_TITLE))
    ap.add_argument("--vmax", type=float, default=3.0)
    ap.add_argument("--dpi", type=int, default=400)
    ap.add_argument("--edge-alpha", type=float, default=0.15)
    ap.add_argument("--edge-lw", type=float, default=0.3)
    ap.add_argument("--tag", default="", help="suffix for the output names")
    args = ap.parse_args()

    filesAB, tsAB = frame_times(RUN_AB)
    filesA, tsA = frame_times(RUN_A)
    filesB, tsB = frame_times(RUN_B)
    wanted = [float(x) for x in args.times.split(",")]

    os.makedirs(args.out, exist_ok=True)
    src_key = "fi_gt" if args.baseline.endswith("true") else "fi_pred"
    fitted = args.baseline.startswith("fit")
    perturbation = args.baseline in PERTURBATION
    if perturbation:
        files0, ts0 = frame_times(RUN_0)

    rows, extent = [], None
    for w in wanted:
        i = int(np.argmin(np.abs(tsAB - w)))
        ia = int(np.argmin(np.abs(tsA - tsAB[i])))
        ib = int(np.argmin(np.abs(tsB - tsAB[i])))
        pts, conn, st, cAB, f1, _ = read_vtu_full(filesAB[i])
        _, _, _, cA, f2, _ = read_vtu_full(filesA[ia])
        _, _, _, cB, f3, _ = read_vtu_full(filesB[ib])

        verts = _hex_footprint_quads(pts, conn, st, cAB)
        pAB = f1.get("ply_id", np.zeros(len(cAB))).astype(int)
        pA = f2.get("ply_id", np.zeros(len(cA))).astype(int)
        pB = f3.get("ply_id", np.zeros(len(cB))).astype(int)
        plies = sorted(np.unique(pAB).tolist())
        gt, pred = f1["fi_gt"], f1["fi_pred"]

        yA = ply_interp(cA, f2[src_key], cAB, pA, pAB, plies)
        yB = ply_interp(cB, f3[src_key], cAB, pB, pAB, plies)
        m = np.isfinite(yA) & np.isfinite(yB) & np.isfinite(gt) & np.isfinite(pred)
        y0 = None
        if perturbation:
            i0 = int(np.argmin(np.abs(ts0 - tsAB[i])))
            _, _, _, c0, f0, _ = read_vtu_full(files0[i0])
            p0 = f0.get("ply_id", np.zeros(len(c0))).astype(int)
            y0 = ply_interp(c0, f0[src_key], cAB, p0, pAB, plies)
            m = m & np.isfinite(y0)

        sup = np.full(len(cAB), np.nan)
        if fitted:
            X = np.column_stack([yA[m], yB[m], np.ones(int(m.sum()))])
            coef, *_ = np.linalg.lstsq(X, gt[m], rcond=None)
            sup[m] = X @ coef
            print(f"t={tsAB[i]:.2f} fit a={coef[0]:.3f} b={coef[1]:.3f} "
                  f"c={coef[2]:.3f}")
        elif perturbation:
            # FI_A + FI_B - FI_0, clipped at zero because a negative failure
            # index has no meaning and only the positive part is ever thresholded
            sup[m] = np.clip(yA[m] + yB[m] - y0[m], 0.0, None)
        else:
            sup[m] = yA[m] + yB[m]

        # laminate-wide numbers, quoted in the caption
        tmask = gt[m] > THR
        print(f"t={tsAB[i]:.2f} laminate: Dice model "
              f"{dice(pred[m] > THR, tmask):.3f}  superposition "
              f"{dice(sup[m] > THR, tmask):.3f} | area truth "
              f"{tmask.mean():.3f} model {(pred[m] > THR).mean():.3f} "
              f"superposition {(sup[m] > THR).mean():.3f}")

        sel = (pAB == args.ply) & m
        if extent is None:
            extent = (float(pts[:, 0].min()), float(pts[:, 0].max()),
                      float(pts[:, 1].min()), float(pts[:, 1].max()))
        stem = f"superpos_diag{args.tag}_ply{args.ply}_t{tsAB[i]:.2f}".replace(".", "p", 1)
        stem = stem.replace(f"t{tsAB[i]:.2f}".replace(".", "p", 1),
                            f"t{int(round(tsAB[i]*100)):03d}")
        names = {}
        for tag, field in (("gt", gt), ("pred", pred), ("sup", sup)):
            png = f"{stem}_{tag}.png"
            _render_mesh_panel_png(
                verts[sel], np.nan_to_num(field[sel]), 0.0, args.vmax,
                extent, os.path.join(args.out, png), dpi=args.dpi,
                edge_alpha=args.edge_alpha, edge_lw=args.edge_lw,
                cmap="viridis")
            names[tag] = png
        rows.append((float(tsAB[i]), names))

    x0, x1, y0, y1 = extent
    out = [HEAD.format(ply=args.ply, baseline=args.baseline, nrow=len(rows))]
    for r, (t, names) in enumerate(rows):
        for c, tag in enumerate(("gt", "pred", "sup")):
            opts = []
            if r == 0:
                title = ["Ground truth", "Graph Transformer",
                         SUP_TITLE[args.baseline]][c]
                opts.append(f"title={{{title}}}")
            if c == 0 and len(rows) > 1:
                opts.append(f"ylabel={{$t={t:.2f}$}}")
            if c == 2 and r == len(rows) - 1:
                # The domain is square and the axis is 0.26\linewidth wide under
                # "axis equal image", so the panel is 0.26\linewidth tall. The
                # colorbar height is set to the same value, otherwise pgfplots
                # sizes it from the default axis height and it comes out
                # noticeably shorter than the panel beside it.
                opts.append(
                    r"colorbar right, colorbar style={scale only axis, "
                    r"width=2.0mm, "
                    r"height=\pgfkeysvalueof{/pgfplots/parent axis height}, "
                    r"ylabel={$\mathrm{FI}^{t}$}, "
                    r"ylabel style={font=\scriptsize}, ytick={0,1,2,3}, "
                    r"yticklabel style={font=\scriptsize}}")
            out.append(CELL.format(opts=", ".join(opts), png=names[tag],
                                   x0=x0, x1=x1, y0=y0, y1=y1))
    out.append(TAIL)

    tex = os.path.join(args.out, f"fig_superposition_extrap{args.tag}.tex")
    with open(tex, "w") as fh:
        fh.write("".join(out))
    print(f"wrote {tex}")


if __name__ == "__main__":
    main()
