#!/usr/bin/env python
"""Two-hole received-attention field against the combination of the single-hole ones.

The panels are

    single hole A | single hole B | superposition A+B | two-hole (actual)

and the reported number is the R^2 of the least-squares fit a*A + b*B + c to the
two-hole field. A and B are interpolated onto the two-hole mesh per ply (linear
inside the hull, nearest outside), the boundary attention sink is clipped at the
99th percentile, and each field is normalised to zero mean and unit standard
deviation before fitting. For display each panel is divided by its own maximum
(YlGnBu, 0 to 1), as in the attention figures of tools/render_attention_field.py.
A low R^2 means that the two-hole attention is not a linear combination of the
single-hole ones.

Usage:
  python tools/make_attention_superposition_figure.py \
      --out <figure dir> --frame 59 --ply 1
"""
import argparse
import os
import sys

import numpy as np
from scipy.interpolate import griddata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from export_fields_for_tikz import (            # noqa: E402
    read_vtu_full, _hex_footprint_quads, _frame_files, _render_mesh_panel_png,
)

RUNS = {"A": "results/attn_onehole_diag_a_step22",
        "B": "results/attn_onehole_diag_b_step22",
        "AB": "results/attn_twohole_diag_step22"}


def load_attn(run, frame):
    p = os.path.join(ROOT, run, "test_results", "attention_analysis_blk1",
                     f"attn_field_frame_{frame:04d}.npz")
    d = np.load(p, allow_pickle=True)
    return d["mesh_pos"], d["received_attn"].astype(float)


def clip_sink(v, q=99.0):
    hi = np.percentile(v, q)
    return np.clip(v, None, hi)


def znorm(v):
    s = v.std()
    return (v - v.mean()) / (s if s > 1e-12 else 1.0)


def ply_interp(src_pos, src_val, dst_pos):
    out = np.full(len(dst_pos), np.nan)
    for z in np.unique(np.round(dst_pos[:, 2], 4)):
        d = np.isclose(dst_pos[:, 2], z)
        s = np.isclose(np.round(src_pos[:, 2], 4), z)
        if s.sum() < 4 or d.sum() == 0:
            continue
        v = griddata(src_pos[s, :2], src_val[s], dst_pos[d, :2], method="linear")
        bad = ~np.isfinite(v)
        if bad.any():
            v[bad] = griddata(src_pos[s, :2], src_val[s], dst_pos[d][bad, :2],
                              method="nearest")
        out[d] = v
    return out


TEX = r"""% Auto-generated by tools/make_attention_superposition_figure.py -- do not edit.
% Received attention, block 1, diagonal two-hole plate, ply {ply}, frame {frame}.
% Each panel is divided by its own maximum after clipping the boundary sink at
% the 99th percentile, so the colour reads as "received attention / panel max"
% on the same 0..1 YlGnBu scale as fig_attention_sim_006/013.tex.
\begin{{tikzpicture}}
\begin{{groupplot}}[
  group style={{group size=4 by 1, horizontal sep=3.0mm}},
  width=0.20\linewidth, height=0.20\linewidth, scale only axis,
  enlargelimits=false, xtick=\empty, ytick=\empty,
  colormap/YlGnBu, point meta min=0, point meta max=1,
  title style={{font=\scriptsize, align=center, text width=0.24\linewidth}},
]
\nextgroupplot[title={{Single hole A}}]
\addplot graphics[xmin={x0:.4g}, xmax={x1:.4g}, ymin={y0:.4g}, ymax={y1:.4g}] {{{stem}_a.png}};
\nextgroupplot[title={{Single hole B}}]
\addplot graphics[xmin={x0:.4g}, xmax={x1:.4g}, ymin={y0:.4g}, ymax={y1:.4g}] {{{stem}_b.png}};
\nextgroupplot[title={{Superposition\\of A and B}}]
\addplot graphics[xmin={x0:.4g}, xmax={x1:.4g}, ymin={y0:.4g}, ymax={y1:.4g}] {{{stem}_sup.png}};
\nextgroupplot[title={{Two holes\\(actual)}}, colorbar right,
  colorbar style={{scale only axis, width=2.0mm,
    height=\pgfkeysvalueof{{/pgfplots/parent axis height}},
    ylabel={{received attention / panel max}},
    ylabel style={{font=\scriptsize}}, yticklabel style={{font=\scriptsize}}}}]
\addplot graphics[xmin={x0:.4g}, xmax={x1:.4g}, ymin={y0:.4g}, ymax={y1:.4g}] {{{stem}_ab.png}};
\end{{groupplot}}
\end{{tikzpicture}}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--frame", type=int, default=59)
    ap.add_argument("--ply", type=int, default=1)
    ap.add_argument("--clip", type=float, default=99.0)
    ap.add_argument("--dpi", type=int, default=400)
    args = ap.parse_args()

    posA, vA = load_attn(RUNS["A"], args.frame)
    posB, vB = load_attn(RUNS["B"], args.frame)
    posAB, vAB = load_attn(RUNS["AB"], args.frame)
    for n, v in (("A", vA), ("B", vB), ("AB", vAB)):
        print(f"{n}: n={len(v)}  raw max {v.max():.4g}  p99 "
              f"{np.percentile(v, 99):.4g}")

    vA, vB, vAB = (clip_sink(v, args.clip) for v in (vA, vB, vAB))
    yA = znorm(ply_interp(posA, vA, posAB))
    yB = znorm(ply_interp(posB, vB, posAB))
    y = znorm(vAB)

    m = np.isfinite(yA) & np.isfinite(yB) & np.isfinite(y)
    X = np.column_stack([yA[m], yB[m], np.ones(int(m.sum()))])
    coef, *_ = np.linalg.lstsq(X, y[m], rcond=None)
    fit = X @ coef
    ss = float(((y[m] - y[m].mean()) ** 2).sum())
    r2 = 1 - float(((fit - y[m]) ** 2).sum()) / ss
    plain = yA[m] + yB[m]
    ssp = 1 - float(((plain - y[m]) ** 2).sum()) / ss
    print(f"\nfit a={coef[0]:.3f} b={coef[1]:.3f} c={coef[2]:.3f}")
    print(f"R2 of the BEST linear combination of A and B : {r2:+.3f}")
    print(f"R2 of the plain sum A+B                      : {ssp:+.3f}")

    # geometry for the panels, taken from the two-hole VTU of the same run
    vtu = _frame_files(os.path.join(ROOT, RUNS["AB"]), "sim_000")[args.frame]
    pts, conn, st, cent, fld, _ = read_vtu_full(vtu)
    verts = _hex_footprint_quads(pts, conn, st, cent)
    ply_id = fld.get("ply_id", np.zeros(len(cent))).astype(int)

    # the attention arrays are per NODE of the graph, one per element centroid,
    # in the same order the VTU lists the cells
    if len(cent) != len(y):
        sys.exit(f"cell count {len(cent)} != attention length {len(y)}")

    sel = (ply_id == args.ply) & m
    full_fit = np.full(len(y), np.nan)
    full_fit[m] = fit

    # The single-hole panels are drawn on THEIR OWN meshes. Drawing them on the
    # two-hole mesh, as the interpolated arrays invite, puts two holes in a
    # panel captioned "single hole" and misleads the reader about what was
    # combined.
    own = {}
    for tag, run, v in (("a", RUNS["A"], znorm(vA)), ("b", RUNS["B"], znorm(vB))):
        f = _frame_files(os.path.join(ROOT, run), "sim_000")[args.frame]
        p2, c2, s2, cen2, fl2, _ = read_vtu_full(f)
        if len(cen2) != len(v):
            sys.exit(f"{run}: cell count {len(cen2)} != attention {len(v)}")
        own[tag] = (_hex_footprint_quads(p2, c2, s2, cen2),
                    fl2.get("ply_id", np.zeros(len(cen2))).astype(int), v)

    on_ab = {"sup": full_fit, "ab": y}
    # Display normalisation: each panel divided by its own max, as in the
    # attention figures. The fit above used the z-normalised fields; this
    # rescaling is for colour only.
    def unit(v):
        v = v - np.nanmin(v)
        m = np.nanmax(v)
        return v / (m if m > 1e-12 else 1.0)
    x0, x1 = float(pts[:, 0].min()), float(pts[:, 0].max())
    y0, y1 = float(pts[:, 1].min()), float(pts[:, 1].max())

    os.makedirs(args.out, exist_ok=True)
    stem = f"attn_superpos_diag_ply{args.ply}_f{args.frame:04d}"
    for tag, f in on_ab.items():
        _render_mesh_panel_png(
            verts[sel], unit(np.nan_to_num(f[sel])), 0.0, 1.0, (x0, x1, y0, y1),
            os.path.join(args.out, f"{stem}_{tag}.png"), dpi=args.dpi,
            edge_alpha=0.15, edge_lw=0.3, cmap="YlGnBu")
    for tag, (vv, pid, v) in own.items():
        s2 = pid == args.ply
        _render_mesh_panel_png(
            vv[s2], unit(np.nan_to_num(v[s2])), 0.0, 1.0, (x0, x1, y0, y1),
            os.path.join(args.out, f"{stem}_{tag}.png"), dpi=args.dpi,
            edge_alpha=0.15, edge_lw=0.3, cmap="YlGnBu")
    tex = os.path.join(args.out, "fig_attention_superposition.tex")
    with open(tex, "w") as fh:
        fh.write(TEX.format(ply=args.ply, frame=args.frame, stem=stem,
                            x0=x0, x1=x1, y0=y0, y1=y1))
    print(f"wrote {tex}")


if __name__ == "__main__":
    main()
